#!/usr/bin/env python3
"""Offline visual regression baseline for the public archive.

Run:
  python3 tests/visual_regression.py --update-baseline  # intentional changes
  python3 tests/visual_regression.py                    # compare / fail on drift

Screenshots are generated by Chromium with local CSS, JS and imagery inlined
rather than depending on live GitHub or external image servers. Browser network
behavior, Vimeo playback, and authenticated publishing must be checked separately.
"""
from __future__ import annotations
import argparse
import base64
import json
import mimetypes
import re
import sys
from functools import lru_cache
from pathlib import Path
from bs4 import BeautifulSoup
from PIL import Image, ImageChops, ImageStat
from playwright.sync_api import sync_playwright

ROOT=Path(__file__).resolve().parents[1]
BASE=ROOT/'tests'/'visual_baselines'
ACTUAL=ROOT/'tests'/'visual_actual'
DIFF=ROOT/'tests'/'visual_diff'
CHROMIUM='/usr/bin/chromium'
RESULTS=[]


@lru_cache(maxsize=500)
def encode(path):
    if path.stat().st_size>3_000_000:return None
    mt=mimetypes.guess_type(str(path))[0] or 'image/jpeg'
    return f'data:{mt};base64,'+base64.b64encode(path.read_bytes()).decode('ascii')


def stylesheet(text, css_file):
    text=re.sub(r'@import\s+url\([^)]*(?:fonts\.googleapis\.com|fonts\.gstatic\.com)[^)]*\);?', '',text)
    def repl(m):
        raw=m.group(2)
        if raw.startswith(('data:','https:','http:','#')):return m.group(0)
        p=(css_file.parent/raw.split('?')[0]).resolve()
        if not p.is_relative_to(ROOT) or not p.is_file():return m.group(0)
        data=encode(p)
        return f'url("{data}")' if data else m.group(0)
    return re.sub(r'url\(\s*([\'\"]?)([^)\'\"]+)\1\s*\)',repl,text)


@lru_cache(maxsize=16)
def inline_site(path):
    full=ROOT/path
    soup=BeautifulSoup(full.read_text(encoding='utf-8'),'html.parser')
    # Offline browser must use actual CSS backgrounds, not missing assets.
    for link in list(soup.find_all('link',rel=lambda v: bool(v and 'stylesheet' in v))):
        href=link.get('href','').split('?')[0]
        loc=(ROOT/href.lstrip('/')).resolve() if href.startswith('/') else (full.parent/href).resolve()
        if loc.is_file() and loc.is_relative_to(ROOT):
            el=soup.new_tag('style')
            el.string=stylesheet(loc.read_text(encoding='utf-8'),loc)
            link.replace_with(el)
        else:link.decompose()
    for style in soup.find_all('style'):
        if style.string:style.string=stylesheet(style.string,full)
    scripts=[]
    for el in list(soup.find_all('script',src=True)):
        src=el.get('src','').split('?')[0]
        loc=(ROOT/src.lstrip('/')).resolve() if src.startswith('/') else (full.parent/src).resolve()
        if loc.is_file() and loc.is_relative_to(ROOT):
            inline=soup.new_tag('script');inline.string=loc.read_text(encoding='utf-8');scripts.append(inline)
        el.decompose()
    for el in soup.find_all('img',src=True):
        raw=el['src'].split('?')[0]
        loc=(ROOT/raw.lstrip('/')).resolve() if raw.startswith('/') else (full.parent/raw).resolve()
        if loc.is_file() and loc.is_relative_to(ROOT):
            encoded=encode(loc)
            if encoded:el['src']=encoded
        el.attrs.pop('srcset',None)
    for sc in scripts:soup.body.append(sc)
    # Disable time-dependent transitions; preserve geometry and accessible focus.
    el=soup.new_tag('style');el.string='*,*::before,*::after{scroll-behavior:auto!important;transition:none!important;animation:none!important;caret-color:transparent!important}';soup.head.append(el)
    return str(soup)


def render(page,kind):
    page.wait_for_timeout(110)
    if kind=='viewer':
        btn=page.locator('article button.article-image-open').first
        if btn.count()==0:raise AssertionError('No viewer control found')
        btn.evaluate('(el)=>el.click()')
        assert page.locator('#ffv-dialog').evaluate('(el)=>el.open'),'viewer failed to open'
        # User-reported regression: measure actual rendered viewer geometry.
        dims=page.locator('#ffv-dialog').evaluate('''el=>{const r=el.getBoundingClientRect();return {cx:r.left+r.width/2,cy:r.top+r.height/2,w:r.width,h:r.height}}''')
        viewport=page.evaluate('({x:document.documentElement.clientWidth/2,y:document.documentElement.clientHeight/2})')
        if abs(dims['cx']-viewport['x'])>3 or abs(dims['cy']-viewport['y'])>3:
            raise AssertionError(f'viewer off-center: dialog={dims} screen={viewport}')
    elif kind=='body':
        target=page.locator('article figure').first
        if target.count():target.evaluate('(el)=>el.scrollIntoView({block:"center"})')
    page.wait_for_timeout(100)


def compare(actual,reference):
    im=Image.open(actual).convert('RGB'); ref=Image.open(reference).convert('RGB')
    if im.size!=ref.size:return 1, None
    dif=ImageChops.difference(im,ref)
    channel=ImageStat.Stat(dif).mean
    score=sum(channel)/(3*255)
    return score,dif


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--update-baseline',action='store_true')
    parser.add_argument('--threshold',type=float,default=.008,help='fraction of average RGB pixel difference')
    args=parser.parse_args()
    BASE.mkdir(exist_ok=True);ACTUAL.mkdir(exist_ok=True);DIFF.mkdir(exist_ok=True)
    cases=[]
    for rel in ['index.html','alike/index.html','mindglassprocedure/index.html','the-black-hole/index.html']:
        for w,h in [(1365,860),(390,844)]:
            for theme in ['light','dark']:
                cases.append((rel,w,h,theme,'top'))
        if rel!='index.html':
            cases.extend([(rel,1365,860,'dark','body'),(rel,1365,860,'dark','viewer'),(rel,390,844,'dark','viewer')])
    failures=[]
    with sync_playwright() as p:
        browser=p.chromium.launch(executable_path=CHROMIUM,headless=True,args=['--no-sandbox'])
        for rel,w,h,theme,kind in cases:
            name=f'{rel.replace("/","-").replace(".html","")}-{w}-{theme}-{kind}.png'
            context=browser.new_context(viewport={'width':w,'height':h},device_scale_factor=1,reduced_motion='reduce')
            page=context.new_page()
            try:
                page.set_content(inline_site(rel),wait_until='domcontentloaded',timeout=25000)
                page.evaluate('(theme)=>document.documentElement.dataset.theme=theme',theme)
                render(page,kind)
                out=ACTUAL/name
                page.screenshot(path=str(out),animations='disabled',full_page=False)
                if args.update_baseline:
                    (BASE/name).write_bytes(out.read_bytes());RESULTS.append({'case':name,'result':'baseline updated'})
                else:
                    ref=BASE/name
                    if not ref.is_file():raise AssertionError('baseline missing: run with --update-baseline')
                    score,dif=compare(out,ref)
                    if score>args.threshold:
                        dif.save(DIFF/name)
                        raise AssertionError(f'image deviation {score:.4f} exceeds {args.threshold:.4f}')
                    RESULTS.append({'case':name,'result':'pass','rgb_difference':round(score,6)})
            except Exception as exc:
                failures.append(f'{name}: {exc}')
                RESULTS.append({'case':name,'result':'fail','detail':str(exc)})
            finally:context.close()
        browser.close()
    report={'mode':'update' if args.update_baseline else 'check','scope':'offline Chromium; no live GitHub/Safari/Vimeo verification','cases':len(cases),'failed':len(failures),'results':RESULTS}
    (ROOT/'tests'/'visual-regression-results.json').write_text(json.dumps(report,indent=2)+'\n')
    for x in failures:print('FAIL',x)
    print('Visual regression:',len(cases)-len(failures),'/',len(cases),'passed')
    return int(bool(failures))

if __name__=='__main__':sys.exit(main())
