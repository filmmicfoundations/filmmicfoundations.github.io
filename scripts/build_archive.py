#!/usr/bin/env python3
"""
Filmmic Foundations — automatically generate the homepage article cards.

HOW IT WORKS:
  1. Add a folder with index.html and article.json to the repository root.
  2. GitHub Actions runs this script whenever you push.
  3. It replaces the article-card block on the homepage and updates sitemap.xml.

This is a build step, not a runtime server. No Python is needed by visitors.
"""
from pathlib import Path
from html import escape
import json
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
HOME = ROOT / "index.html"
BASE_URL = "https://filmmicfoundations.github.io/"
START = "<!-- ARTICLES START:"
END = "<!-- ARTICLES END -->"

def read_articles():
    articles = []
    for folder in ROOT.iterdir():
        if not folder.is_dir() or folder.name.startswith("."):
            continue
        metadata = folder / "article.json"
        if not metadata.exists():
            continue
        if not (folder / "index.html").is_file():
            raise ValueError(f"{folder.name}: missing index.html")
        data = json.loads(metadata.read_text(encoding="utf-8"))
        for required in ("title", "description", "image"):
            if not isinstance(data.get(required), str) or not data[required].strip():
                raise ValueError(f"{metadata}: missing '{required}'")
        if not (folder / data["image"]).is_file():
            raise ValueError(f"{metadata}: image '{data['image']}' does not exist")
        data["slug"] = folder.name
        articles.append(data)
    return sorted(articles, key=lambda item: (item.get("order", 9999), item["title"].lower()))

def card(article):
    slug = escape(article["slug"], quote=True)
    image = escape(article["image"], quote=True)
    alt = escape(article.get("image_alt", article["title"]), quote=True)
    kind = escape(article.get("type", "FILM ANALYSIS"))
    year = escape(str(article.get("year", "")))
    title = escape(article["title"])
    desc = escape(article["description"])
    return f"""<a class="entry" href="{slug}/">
  <img src="{slug}/{image}" alt="{alt}" loading="lazy">
  <div class="entry-body">
    <div class="tag">{kind} · {year}</div>
    <h3>{title}</h3>
    <p>{desc}</p>
    <span class="read">Read full research article →</span>
  </div>
</a>"""

def main():
    articles = read_articles()
    if not articles:
        raise ValueError("No articles found. Add an article.json to an article folder.")
    html = HOME.read_text(encoding="utf-8")
    pattern = re.compile(r"<!-- ARTICLES START:.*?<!-- ARTICLES END -->", re.DOTALL)
    replacement = ("<!-- ARTICLES START: generated by scripts/build_archive.py; do not edit this block manually. -->\n"
                   + "\n".join(card(a) for a in articles) + "\n<!-- ARTICLES END -->")
    if not pattern.search(html):
        raise ValueError("Homepage is missing ARTICLES START/END markers.")
    html = pattern.sub(lambda _: replacement, html, count=1)
    html = re.sub(r"<small>\\d+ PUBLICATION(?:S)?</small>",
                  f"<small>{len(articles):02d} PUBLICATION{'S' if len(articles) != 1 else ''}</small>", html)
    HOME.write_text(html, encoding="utf-8")

    # Generate search-engine-friendly sitemap for every article.
    root = ET.Element("urlset", xmlns="http://www.sitemaps.org/schemas/sitemap/0.9")
    for url in [BASE_URL] + [BASE_URL + a["slug"] + "/" for a in articles]:
        ET.SubElement(ET.SubElement(root, "url"), "loc").text = url
    ET.indent(root, space="  ")
    ET.ElementTree(root).write(ROOT / "sitemap.xml", encoding="unicode", xml_declaration=True)
    print(f"Generated {len(articles)} article card(s) and sitemap.xml")

if __name__ == "__main__":
    main()
